"""Analysis of round 2 (pecto-hga-reduced-r2): the reduced hybrid GA against the full one, and against PECTOACO.

Implements the analysis plan and decision rule of the round-2 journals, written on 2026-10-27 before any result.
Reuses the exact tests of round 1 (pecto-hga-vs-aco-1-ga-evals/analyze.py). Pure Python.
Usage, from the experiments directory:  python -I -B pecto-hga-reduced-r2-1-181k/analyze.py
Writes pecto-hga-reduced-r2-1-181k/analysis.md and prints it. Works on partial results.
"""
import importlib.util
import json
import os
import statistics
import sys
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
WS = os.path.dirname(HERE)
spec = importlib.util.spec_from_file_location("r1", os.path.join(WS, "pecto-hga-vs-aco-1-ga-evals", "analyze.py"))
r1 = importlib.util.module_from_spec(spec)
spec.loader.exec_module(r1)

PARTS = [("181,501 evaluations", "pecto-hga-reduced-r2-1-181k"),
         ("1,000,000 evaluations", "pecto-hga-reduced-r2-2-1m"),
         ("600 s", "pecto-hga-reduced-r2-3-600s")]
ACO_TIME = "pecto-hga-vs-aco-4-aco-time"
INSTANCES, BEDS_USED, MIN_GAP, ALPHA = r1.INSTANCES, r1.BEDS_USED, r1.MIN_GAP, r1.ALPHA
fmt, fmtp, med = r1.fmt, r1.fmtp, r1.med


def rows(experiment):
    path = os.path.join(WS, experiment, "runs.jsonl")
    out = []
    if os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            for line in f:
                if line.strip():
                    r = json.loads(line)
                    r.update(r.pop("metrics", {}) or {})
                    out.append(r)
    return out


def verdict(gaps):
    if len(gaps) < 2:
        return "n/a", float("nan"), float("nan"), float("nan")
    m = statistics.mean(gaps)
    half = r1.t975(len(gaps) - 1) * statistics.stdev(gaps) / len(gaps) ** 0.5
    p = r1.wilcoxon_exact(gaps)
    v = "ACCEPTED" if m + half < MIN_GAP else "REJECTED"
    if v == "ACCEPTED" and p < ALPHA and m <= -MIN_GAP:
        v = "ACCEPTED, BETTER"
    return v, m - half, m + half, p


def main():
    out = ["# Round 2: reduced hybrid GA vs the full GA", "",
           "_Generated by analyze.py. Reduced = tournament-only selection, no offspring mutation, no stagnation "
           "response, no SA. Gap = (reduced - default) / default of the run with the same instance and repeat; "
           "negative means the reduced GA is cheaper._", "",
           "## Primary (decision rule)", "",
           "| budget | pairs | mean gap % | 95 % interval | better/worse | p (Wilcoxon) | verdict |",
           "|---|---|---|---|---|---|---|"]
    per_budget = {}
    accepted_all, complete = True, True
    for label, exp in PARTS:
        rs = rows(exp)
        cost = {(r["config"], r["instance"], r["repeat"]): r["bestCost"] for r in rs}
        gaps = [(inst, (cost[("reduced", inst, rep)] - c) / c * 100)
                for (cfg, inst, rep), c in cost.items() if cfg == "default" and ("reduced", inst, rep) in cost]
        per_budget[label] = (rs, gaps)
        g = [x for _, x in gaps]
        v, lo, hi, p = verdict(g)
        if len(g) < 50:
            complete = False
        accepted_all &= v.startswith("ACCEPTED")
        out.append(f"| {label} | {len(g)} | {fmt(statistics.mean(g), 3) if g else 'n/a'} | {fmt(lo, 3)} … {fmt(hi, 3)} | "
                   f"{sum(1 for x in g if x < 0)}/{sum(1 for x in g if x > 0)} | {fmtp(p)} | {v} |")
    out += ["", f"**The reduced GA becomes the recommended default: {'yes' if accepted_all else 'no'}** "
                "(accepted at all three budgets required)"
            + ("" if complete else " — *provisional: not all 50 pairs per budget are in*"), "",
            "### Mean gap % by instance", "",
            "| budget | " + " | ".join(f"{i} ({BEDS_USED[i]:.0%})" for i in INSTANCES) + " |",
            "|---|" + "---|" * len(INSTANCES)]
    for label, (rs, gaps) in per_budget.items():
        cells = []
        for inst in INSTANCES:
            g = [x for i, x in gaps if i == inst]
            cells.append(f"{fmt(statistics.mean(g), 3)} ({sum(1 for x in g if x < 0)}/{len(g)})" if g else "n/a")
        out.append(f"| {label} | " + " | ".join(cells) + " |")
    out += ["", "(k/n) pairs in which the reduced GA is cheaper.", "",
            "## Secondary", "",
            "### Reduced GA (600 s) vs PECTOACO (600 s, " + ACO_TIME + "), unpaired", "",
            "| instance | median reduced GA | median full GA | median PECTOACO | gap reduced vs ACO % | A12 | p | Holm p |",
            "|---|---|---|---|---|---|---|---|"]
    rs600 = per_budget["600 s"][0]
    aco = rows(ACO_TIME)
    res = []
    for inst in INSTANCES:
        g = [r["bestCost"] for r in rs600 if r["config"] == "reduced" and r["instance"] == inst]
        f = [r["bestCost"] for r in rs600 if r["config"] == "default" and r["instance"] == inst]
        a = [r["bestCost"] for r in aco if r["config"] == "default" and r["instance"] == inst]
        gap = (med(g) - med(a)) / med(a) * 100 if g and a else float("nan")
        res.append((inst, g, f, a, gap, r1.a12(g, a), r1.mann_whitney_exact(g, a)))
    for (inst, g, f, a, gap, eff, p), h in zip(res, r1.holm([x[6] for x in res])):
        out.append(f"| {inst} | {fmt(med(g))} | {fmt(med(f))} | {fmt(med(a))} | {fmt(gap, 2)} | {fmt(eff, 2)} | "
                   f"{fmtp(p)} | {fmtp(h)} |")
    out += ["", "### Activity at the end (medians over all instances)", "",
            "| budget | configuration | duplicates | diversity | stagnation | generations | evaluations | eval/s |",
            "|---|---|---|---|---|---|---|---|"]
    for label, (rs, _) in per_budget.items():
        for cfg in ["default", "reduced"]:
            sel = [r for r in rs if r["config"] == cfg]
            if not sel:
                continue
            m = lambda k: med([float(r[k]) for r in sel if k in r])
            eps = med([r["evaluations"] / max(1.0, r["elapsedMs"] / 1000) for r in sel])
            out.append(f"| {label} | {cfg} | {fmt(m('duplicates'), 3)} | {fmt(m('diversity'), 4)} | "
                       f"{fmt(m('stagnation'), 0)} | {fmt(m('iterations'), 0)} | {fmt(m('evaluations'), 0)} | {fmt(eps, 0)} |")
    # anytime at 600 s
    trace = defaultdict(list)
    path = os.path.join(WS, PARTS[2][1], "trace.jsonl")
    if os.path.exists(path):
        for line in open(path, encoding="utf-8"):
            if line.strip():
                t = json.loads(line)
                trace[(t["config"], t["instance"], t["repeat"])].append(t)
    checkpoints = [15, 30, 60, 120, 300, 600]
    out += ["", "### Anytime at 600 s: median best cost", "",
            "| instance | configuration | " + " | ".join(f"{c} s" for c in checkpoints) + " |",
            "|---|---|" + "---|" * len(checkpoints)]
    for inst in INSTANCES:
        for cfg in ["default", "reduced"]:
            finals = {r["repeat"]: r for r in rs600 if r["config"] == cfg and r["instance"] == inst}
            cells = []
            for c in checkpoints:
                vals = []
                for rep, r in finals.items():
                    if c >= r["elapsedMs"] / 1000:
                        vals.append(r["bestCost"])
                    else:
                        v = r1.best_at(trace.get((cfg, inst, rep), []), "time", c)
                        if v is not None:
                            vals.append(v)
                cells.append(f"{fmt(med(vals))} ({len(vals)})" if vals else "n/a")
            out.append(f"| {inst} | {cfg} | " + " | ".join(cells) + " |")
    text = "\n".join(out) + "\n"
    with open(os.path.join(HERE, "analysis.md"), "w", encoding="utf-8") as f:
        f.write(text)
    sys.stdout.reconfigure(encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
