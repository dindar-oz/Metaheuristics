"""Analysis of round 3 (pecto-hga-components-r3): which hybrid GA components are worth keeping.

Implements the analysis plan and decision rule of the round-3 journals, written on 2026-10-27 before any result,
and combines them with round 1 (pecto-hga-vs-aco-6-ga-ablation-1m, recomputed from its runs). Reuses the exact tests
of round 1 (pecto-hga-vs-aco-1-ga-evals/analyze.py). Pure Python.
Usage, from the experiments directory:  python -I -B pecto-hga-components-r3-1-1m/analyze.py
Writes pecto-hga-components-r3-1-1m/analysis.md and prints it. Works on partial results.
"""
import importlib.util
import json
import os
import statistics
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
WS = os.path.dirname(HERE)
_spec = importlib.util.spec_from_file_location("r1", os.path.join(WS, "pecto-hga-vs-aco-1-ga-evals", "analyze.py"))
r1 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(r1)
fmt, fmtp, med, holm, t975, wilcoxon = r1.fmt, r1.fmtp, r1.med, r1.holm, r1.t975, r1.wilcoxon_exact
INSTANCES, MIN_GAP, ALPHA = r1.INSTANCES, r1.MIN_GAP, r1.ALPHA

BUDGETS = [("1M evaluations", "pecto-hga-components-r3-1-1m"), ("300 s", "pecto-hga-components-r3-2-300s")]
ROUND1 = "pecto-hga-vs-aco-6-ga-ablation-1m"
KEPT = ["R-seeding", "R-repair", "R-cheaperBias", "R-recombination", "R-LS", "R-ageing", "R-tournament"]
DROPPED = ["R+mutation", "R+stagnation", "R+SA", "R+SAlight", "R+SAstrong"]
SETTINGS = ["R+LS3", "R+LS30"]
SA_VARIANTS = ["R+SA", "R+SAlight", "R+SAstrong"]
# component: (round-3 variant(s), round-1 variant, how round 1's verdict reads for keeping the component)
COMPONENTS = [
    ("greedy-based seeding", ["R-seeding"], "seedRandom", "removal"),
    ("ARX best-insertion repair", ["R-repair"], "xRandomRepair", "removal"),
    ("ARX cheaper-route bias", ["R-cheaperBias"], "xUnbiased", "removal"),
    ("recombination (ARX vs clone)", ["R-recombination"], "xNone", "removal"),
    ("local search of the offspring", ["R-LS"], "noLS", "removal"),
    ("age protection", ["R-ageing"], "noAgeing", "removal"),
    ("tournament-only selection", ["R-tournament"], "selTournament", "adoption"),
    ("offspring mutation", ["R+mutation"], "mNone", "removal"),
    ("stagnation response", ["R+stagnation"], "noStagnation", "removal"),
    ("SA on the best individual", SA_VARIANTS, "noSA", "removal"),
]


def rows(experiment):
    out = []
    path = os.path.join(WS, experiment, "runs.jsonl")
    if os.path.exists(path):
        for line in open(path, encoding="utf-8"):
            if line.strip():
                r = json.loads(line)
                r.update(r.pop("metrics", {}) or {})
                out.append(r)
    return out


def gaps_to(rs, base, cfg):
    cost = {(r["config"], r["instance"], r["repeat"]): r["bestCost"] for r in rs}
    return [(inst, (cost[(cfg, inst, rep)] - c) / c * 100)
            for (b, inst, rep), c in cost.items() if b == base and (cfg, inst, rep) in cost]


def stats(g):
    if len(g) < 2:
        return float("nan"), float("nan"), float("nan"), float("nan")
    m = statistics.mean(g)
    half = t975(len(g) - 1) * statistics.stdev(g) / len(g) ** 0.5
    return m, m - half, m + half, wilcoxon(g)


def label(role, m, lo, hi, h):
    if m != m:
        return "n/a"
    if role == "kept":
        if h < ALPHA and m >= MIN_GAP:
            return "NEEDED"
        return "NOT NEEDED" if hi < MIN_GAP else "UNDECIDED"
    if role == "dropped":
        if h < ALPHA and m <= -MIN_GAP:
            return "HELPS"
        return "DOES NOT HELP" if lo > -MIN_GAP else "UNDECIDED"
    if role == "setting":
        if h < ALPHA and m <= -MIN_GAP:
            return "BETTER THAN LS10"
        if h < ALPHA and m >= MIN_GAP:
            return "WORSE THAN LS10"
        return "SAME AS LS10"
    return "reference"


def role_of(cfg):
    return "kept" if cfg in KEPT else "dropped" if cfg in DROPPED else "setting" if cfg in SETTINGS else "reference"


def round1_verdicts():
    rs = rows(ROUND1)
    configs = sorted({r["config"] for r in rs} - {"default"})
    values = {(r["config"], r["instance"], r["repeat"]): r["bestCost"] for r in rs}
    gaps = {c: [x for _, _, x in r1.paired_gaps(values, c)] for c in configs}
    ps = [wilcoxon(gaps[c]) if gaps[c] else float("nan") for c in configs]
    return {c: (r1.label(gaps[c], h)[0], statistics.mean(gaps[c]) if gaps[c] else float("nan"))
            for c, h in zip(configs, holm(ps))}


def main():
    out = ["# Round 3: which hybrid GA components are worth keeping", "",
           "_Generated by analyze.py. R = reduced GA (mixed greedy seeding, ARX with cheaper-route bias and "
           "best-insertion repair, local search 10, tournament-only selection, age protection; no mutation, no "
           "stagnation response, no SA). Gap = (variant - R) / R of the run with the same instance and repeat; "
           "positive means the variant is worse. New instances (instance seed 43) and seeds (base 20261028)._", ""]
    verdicts = {}  # (budget, cfg) -> label
    complete = True
    for budget, exp in BUDGETS:
        rs = rows(exp)
        variants = [c for c in dict.fromkeys(r["config"] for r in rs) if c != "reduced"]
        order = ["full"] + KEPT + DROPPED + SETTINGS
        variants = [c for c in order if c in variants]
        res = {c: gaps_to(rs, "reduced", c) for c in variants}
        st = {c: stats([x for _, x in res[c]]) for c in variants}
        hp = dict(zip(variants, holm([st[c][3] for c in variants])))
        out += [f"## {budget} ({exp})", "",
                "| role | variant | pairs | mean gap % | 95 % interval | better/worse | p | Holm p | verdict | "
                + " | ".join(INSTANCES) + " |",
                "|---|---|---|---|---|---|---|---|---|" + "---|" * len(INSTANCES)]
        for c in variants:
            g = [x for _, x in res[c]]
            if len(g) < 50:
                complete = False
            m, lo, hi, p = st[c]
            v = label(role_of(c), m, lo, hi, hp[c])
            verdicts[(budget, c)] = v
            per = " | ".join(fmt(statistics.mean([x for i, x in res[c] if i == inst]), 2)
                             if any(i == inst for i, _ in res[c]) else "n/a" for inst in INSTANCES)
            out.append(f"| {role_of(c)} | {c} | {len(g)} | {fmt(m, 3)} | {fmt(lo, 3)} … {fmt(hi, 3)} | "
                       f"{sum(1 for x in g if x < 0)}/{sum(1 for x in g if x > 0)} | {fmtp(p)} | {fmtp(hp[c])} | "
                       f"{v} | {per} |")
        out += ["", "| configuration | duplicates | diversity | stagnation | generations | evaluations | eval/s |",
                "|---|---|---|---|---|---|---|"]
        for c in ["reduced"] + variants:
            sel = [r for r in rs if r["config"] == c]
            g = lambda k: med([float(r[k]) for r in sel if k in r])
            eps = med([r["evaluations"] / max(1.0, r["elapsedMs"] / 1000) for r in sel])
            out.append(f"| {c} | {fmt(g('duplicates'), 3)} | {fmt(g('diversity'), 4)} | {fmt(g('stagnation'), 0)} | "
                       f"{fmt(g('iterations'), 0)} | {fmt(g('evaluations'), 0)} | {fmt(eps, 0)} |")
        out.append("")

    # final classification, round 1 + round 3
    r1v = round1_verdicts()
    out += ["## Final classification (decision rule of round 3)", "",
            "| component | round 1 (1M, from full GA) | round 3, 1M | round 3, 300 s | FINAL |", "|---|---|---|---|---|"]
    for name, r3cfgs, r1cfg, reading in COMPONENTS:
        v1, m1 = r1v.get(r1cfg, ("n/a", float("nan")))
        if reading == "adoption":   # removing the roulette share was HARMFUL in round 1 = tournament-only is better
            keep1 = {"HARMFUL": "keep", "ESSENTIAL": "drop"}.get(v1, "?")
        else:
            keep1 = {"ESSENTIAL": "keep", "REMOVABLE": "drop", "HARMFUL": "drop"}.get(v1, "?")
        cells, keeps = [], []
        for budget, _ in BUDGETS:
            vs = [verdicts.get((budget, c)) for c in r3cfgs if (budget, c) in verdicts]
            if not vs:
                cells.append("not tested")
                continue
            if len(r3cfgs) > 1:    # SA: judged on its best setting
                v = "HELPS" if "HELPS" in vs else "DOES NOT HELP" if all(x == "DOES NOT HELP" for x in vs) else "UNDECIDED"
                cells.append(f"{v} ({', '.join(f'{c}: {x}' for c, x in zip(r3cfgs, vs))})")
            else:
                v = vs[0]
                cells.append(v)
            keeps.append("keep" if v in ("NEEDED", "HELPS") else "drop" if v in ("NOT NEEDED", "DOES NOT HELP") else "?")
        if keeps and all(k == "keep" for k in keeps):
            final, way = "**WORTH KEEPING**", "keep"
        elif keeps and all(k == "drop" for k in keeps):
            final, way = "**NOT WORTH KEEPING**", "drop"
        elif "keep" in keeps and "drop" in keeps:
            final, way = "**BUDGET-DEPENDENT**", None
        else:
            final, way = "UNDECIDED", None
        if way:
            final += " — " + ("NEW (round 1 inconclusive)" if keep1 == "?" else "CONFIRMED by round 1" if keep1 == way
                              else "CONTRADICTS ROUND 1")
        out.append(f"| {name} | {v1} ({fmt(m1, 2)} %, {r1cfg}) → {keep1} | {cells[0]} | {cells[1]} | {final} |")
    out += ["", "Round 1: gap of removing the component from the full GA (for tournament-only selection: of using "
                "tournament only instead of the mix), verdict by round 1's rule. Round 3: verdict of the variant "
                "of R. FINAL is decided by round 3 (every budget the component was tested at); round 1 is reported beside it."
            + ("" if complete else " *Provisional: not all 50 pairs per variant are in.*"), ""]
    text = "\n".join(out) + "\n"
    with open(os.path.join(HERE, "analysis.md"), "w", encoding="utf-8") as f:
        f.write(text)
    sys.stdout.reconfigure(encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
