"""Analysis of pecto-best-aco-vs-hga: the best PECTOACO against the best hybrid GA on T8-T10.

Implements the analysis plan and decision rule of the journals, written on 2026-10-28 before any result. Reuses the
exact tests of round 1 (pecto-hga-vs-aco-1-ga-evals/analyze.py). Pure Python.
Usage, from the experiments directory:  python -I -B pecto-best-aco-vs-hga-1-hga-600s/analyze.py
Writes pecto-best-aco-vs-hga-1-hga-600s/analysis.md and prints it. Works on partial results.
"""
import importlib.util
import json
import os
import statistics
import sys
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
WS = os.path.dirname(HERE)
_spec = importlib.util.spec_from_file_location("r1", os.path.join(WS, "pecto-hga-vs-aco-1-ga-evals", "analyze.py"))
r1 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(r1)
fmt, fmtp, med, holm, t975, a12 = r1.fmt, r1.fmtp, r1.med, r1.holm, r1.t975, r1.a12
mann_whitney, wilcoxon = r1.mann_whitney_exact, r1.wilcoxon_exact
ALPHA, MIN_GAP = 0.05, 0.1

PREFIX = "pecto-best-aco-vs-hga"
INSTANCES = ["T8", "T9", "T10"]
HGA_CONFIGS = ["R", "R+LS30", "R+SA+LS30"]
# budget: (HGA part, ACO part, pre-registered primary HGA, anytime key, checkpoints)
BUDGETS = [
    ("600 s", f"{PREFIX}-1-hga-600s", f"{PREFIX}-2-aco-600s", "R+LS30", "elapsedMs", [15, 30, 60, 120, 300, 600]),
    ("181,501 evaluations", f"{PREFIX}-3-hga-181k", f"{PREFIX}-4-aco-181k", "R", "evaluations",
     [10000, 25000, 50000, 100000, 181501]),
]
WITHIN = [("R+LS30", "R"), ("R+SA+LS30", "R+LS30")]


def rows(experiment):
    out = []
    path = os.path.join(WS, experiment, "runs.jsonl")
    if os.path.exists(path):
        for line in open(path, encoding="utf-8"):
            if line.strip():
                r = json.loads(line)
                r.update(r.pop("metrics", {}) or {})
                out.append(r)
    return out


def traces(experiment):
    out = defaultdict(list)
    path = os.path.join(WS, experiment, "trace.jsonl")
    if os.path.exists(path):
        for line in open(path, encoding="utf-8"):
            if line.strip():
                t = json.loads(line)
                out[(t["config"], t["instance"], int(t["repeat"]))].append(t)
    return out


def costs(rs, cfg, inst):
    return [r["bestCost"] for r in rs if r["config"] == cfg and r["instance"] == inst]


def versus(hga, aco, cfg):
    """PECTOACO against one HGA configuration, per instance, Holm over the instances."""
    res = []
    for inst in INSTANCES:
        x, y = costs(hga, cfg, inst), costs(aco, "default", inst)
        p = mann_whitney(x, y) if x and y else float("nan")
        gap = (med(x) - med(y)) / med(y) * 100 if x and y else float("nan")
        res.append([inst, len(x), len(y), med(x), med(y), gap, a12(x, y), p])
    for r, h in zip(res, holm([r[7] for r in res])):
        r.append(h)
        r.append("n/a" if h != h else "HGA" if h < ALPHA and r[5] <= -MIN_GAP
                 else "PECTOACO" if h < ALPHA and r[5] >= MIN_GAP else "tie")
    return res


def verdict(res):
    hga = sum(1 for r in res if r[-1] == "HGA")
    aco = sum(1 for r in res if r[-1] == "PECTOACO")
    if any(r[-1] == "n/a" for r in res):
        return "n/a (incomplete)"
    if hga >= 2 and aco == 0:
        return "HGA better"
    if aco >= 2 and hga == 0:
        return "PECTOACO better"
    return "instance-dependent: " + ", ".join(f"{r[0]} {r[-1]}" for r in res)


def versus_table(res, title):
    out = [f"### {title}", "",
           "| instance | n HGA/ACO | median HGA | median PECTOACO | gap % (HGA-ACO)/ACO | A12 (HGA beats ACO) | p | Holm p | winner |",
           "|---|---|---|---|---|---|---|---|---|"]
    for inst, nx, ny, mx, my, gap, a, p, h, w in res:
        out.append(f"| {inst} | {nx}/{ny} | {fmt(mx)} | {fmt(my)} | {fmt(gap, 2)} | {fmt(a, 2)} | {fmtp(p)} | {fmtp(h)} | {w} |")
    out += ["", f"**Verdict: {verdict(res)}**", ""]
    return out


def paired(hga, cfg, base):
    c = {(r["config"], r["instance"], r["repeat"]): r["bestCost"] for r in hga}
    return [(inst, (c[(cfg, inst, rep)] - v) / v * 100) for (b, inst, rep), v in c.items()
            if b == base and (cfg, inst, rep) in c]


def best_at(lines, key, checkpoint):
    best = float("nan")
    for t in sorted(lines, key=lambda t: t[key]):
        if t[key] > checkpoint:
            break
        best = t["bestCost"]
    return best


def main():
    out = ["# Best PECTOACO vs best hybrid GA on T8-T10", "",
           "_Generated by analyze.py. Instance seed 44 (new to both algorithms), seeds base 20261029, repeats 0-9. "
           "HGA: R = reduced GA (tournament only, no mutation, no stagnation response, no SA, local search 10); "
           "R+LS30 = local search 30; R+SA+LS30 = also SA 25 -> 0.1, x0.95, 1 neighbor. PECTOACO: tuned defaults "
           "(2 explorers, rate 0.05, beta 0.5, deposit 0.05)._", ""]
    for budget, hga_exp, aco_exp, primary, key, checkpoints in BUDGETS:
        hga, aco = rows(hga_exp), rows(aco_exp)
        out += [f"## {budget}", ""]
        out += versus_table(versus(hga, aco, primary), f"Primary: PECTOACO vs {primary} (pre-registered)")
        for cfg in HGA_CONFIGS:
            if cfg != primary:
                out += versus_table(versus(hga, aco, cfg), f"Secondary: PECTOACO vs {cfg}")

        # within the HGA, paired
        out += ["### Within the HGA (paired by instance and repeat)", "",
                "| comparison | pairs | mean gap % | 95 % interval | better/worse | p | Holm p | verdict | "
                + " | ".join(INSTANCES) + " |", "|---|---|---|---|---|---|---|---|" + "---|" * len(INSTANCES)]
        stats = []
        for cfg, base in WITHIN:
            g = paired(hga, cfg, base)
            x = [v for _, v in g]
            m = statistics.mean(x) if x else float("nan")
            half = t975(len(x) - 1) * statistics.stdev(x) / len(x) ** 0.5 if len(x) > 1 else float("nan")
            stats.append((cfg, base, g, x, m, half, wilcoxon(x) if x else float("nan")))
        for (cfg, base, g, x, m, half, p), h in zip(stats, holm([s[6] for s in stats])):
            v = "n/a" if h != h else "BETTER" if h < ALPHA and m <= -MIN_GAP else "WORSE" if h < ALPHA and m >= MIN_GAP else "SAME"
            per = " | ".join(fmt(statistics.mean([d for i, d in g if i == inst]), 2) if any(i == inst for i, _ in g)
                             else "n/a" for inst in INSTANCES)
            out.append(f"| {cfg} vs {base} | {len(x)} | {fmt(m, 3)} | {fmt(m - half, 3)} … {fmt(m + half, 3)} | "
                       f"{sum(1 for d in x if d < 0)}/{sum(1 for d in x if d > 0)} | {fmtp(p)} | {fmtp(h)} | {v} | {per} |")
        out.append("")

        # anytime
        tr = {**traces(hga_exp), **{("PECTOACO",) + k[1:]: v for k, v in traces(aco_exp).items()}}
        unit = "s" if key == "elapsedMs" else ""
        scale = 1000 if key == "elapsedMs" else 1
        out += [f"### Anytime: median best cost", "",
                "| instance | configuration | " + " | ".join(f"{c:,}{unit}" for c in checkpoints) + " |",
                "|---|---|" + "---|" * len(checkpoints)]
        for inst in INSTANCES:
            for cfg in HGA_CONFIGS + ["PECTOACO"]:
                runs_ = [v for k, v in tr.items() if k[0] == cfg and k[1] == inst]
                if not runs_:
                    continue
                cells = []
                for c in checkpoints:
                    vals = [best_at(lines, key, c * scale) for lines in runs_]
                    vals = [v for v in vals if v == v]
                    cells.append(fmt(med(vals)) if vals else "n/a")
                out.append(f"| {inst} | {cfg} | " + " | ".join(cells) + " |")
        out.append("")

        # activity and load
        out += ["### Activity at the end (medians)", "",
                "| configuration | instance | iterations | evaluations | eval/s | diversity | duplicates |",
                "|---|---|---|---|---|---|---|"]
        for cfg, rs in [(c, hga) for c in HGA_CONFIGS] + [("PECTOACO", aco)]:
            for inst in INSTANCES:
                sel = [r for r in rs if r["config"] == (cfg if cfg != "PECTOACO" else "default") and r["instance"] == inst]
                if not sel:
                    continue
                g = lambda k: fmt(med([float(r[k]) for r in sel if k in r]), 4 if k == "diversity" else 3 if k == "duplicates" else 0)
                eps = fmt(med([r["evaluations"] / max(1.0, r["elapsedMs"] / 1000) for r in sel]), 0)
                out.append(f"| {cfg} | {inst} | {g('iterations')} | {g('evaluations')} | {eps} | {g('diversity')} | {g('duplicates')} |")
        out.append("")
        if key == "elapsedMs":
            out += ["Load check (evaluations per second by finishing order, every tenth run):", ""]
            allr = sorted([(str(r.get("finished", "")), r) for r in hga + aco], key=lambda t: t[0])
            for i, (_, r) in enumerate(allr):
                if i % 10 == 0:
                    out.append(f"- #{i}: {r['config']} {r['instance']} rep {r['repeat']}: "
                               f"{r['evaluations'] / max(1.0, r['elapsedMs'] / 1000):,.0f} eval/s")
            out.append("")
    text = "\n".join(out) + "\n"
    with open(os.path.join(HERE, "analysis.md"), "w", encoding="utf-8") as f:
        f.write(text)
    sys.stdout.reconfigure(encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
